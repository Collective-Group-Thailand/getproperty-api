import { bahtText, formatThb, thaiDate } from './thai-text';

describe('Thai text for contracts', () => {
  it.each([
    ['0', 'ศูนย์บาทถ้วน'],
    ['1', 'หนึ่งบาทถ้วน'],
    ['11', 'สิบเอ็ดบาทถ้วน'],
    ['21', 'ยี่สิบเอ็ดบาทถ้วน'],
    ['101', 'หนึ่งร้อยเอ็ดบาทถ้วน'],
    ['4500', 'สี่พันห้าร้อยบาทถ้วน'],
    ['13500.00', 'หนึ่งหมื่นสามพันห้าร้อยบาทถ้วน'],
    ['1250.50', 'หนึ่งพันสองร้อยห้าสิบบาทห้าสิบสตางค์'],
    ['0.25', 'ยี่สิบห้าสตางค์'],
    ['1000000', 'หนึ่งล้านบาทถ้วน'],
    ['2511021.01', 'สองล้านห้าแสนหนึ่งหมื่นหนึ่งพันยี่สิบเอ็ดบาทหนึ่งสตางค์'],
  ])('%s → %s', (amount, text) => {
    expect(bahtText(amount)).toBe(text);
  });

  it('formats money with separators and dates in the Buddhist era', () => {
    expect(formatThb('13500')).toBe('13,500.00');
    expect(formatThb('1234567.891')).toBe('1,234,567.89');
    expect(thaiDate('2026-11-01')).toBe('1 พฤศจิกายน พ.ศ. 2569');
    expect(thaiDate('2027-02-28')).toBe('28 กุมภาพันธ์ พ.ศ. 2570');
  });
});
