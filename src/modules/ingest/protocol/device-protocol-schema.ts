import { defaultMetadataStorage } from 'class-transformer/cjs/storage';
import { getMetadataStorage } from 'class-validator';
import { validationMetadatasToSchemas } from 'class-validator-jsonschema';

import { Command, CommandAck } from './command.dto';
import { BusConfig, GatewayConfig, MeterConfig } from './config.dto';
import * as enums from './enums';
import { DeviceEvent } from './events.dto';
import { Health, MeterHealth } from './health.dto';
import { Reading, TelemetryBatch } from './telemetry.dto';

export const DEVICE_PROTOCOL_SCHEMA_ID = 'https://getproperty.co/contract/device-protocol.json';
export const JSON_SCHEMA_DRAFT = 'https://json-schema.org/draft/2020-12/schema';

/** The payload classes published to `getproperty-edge`, in topic order (device-protocol.md §2). */
export const PROTOCOL_PAYLOADS = [
  TelemetryBatch,
  Reading,
  Health,
  MeterHealth,
  DeviceEvent,
  GatewayConfig,
  BusConfig,
  MeterConfig,
  Command,
  CommandAck,
] as const;

/** Topic → payload definition (device-protocol.md §2); `<gatewayId>` is the uuid of the publishing gateway. */
export const TOPICS = {
  'gp/v1/<gatewayId>/telemetry': {
    direction: 'gateway_to_cloud',
    qos: 1,
    retained: false,
    payload: 'TelemetryBatch',
  },
  'gp/v1/<gatewayId>/health': { direction: 'gateway_to_cloud', qos: 1, retained: false, payload: 'Health' },
  'gp/v1/<gatewayId>/events': {
    direction: 'gateway_to_cloud',
    qos: 1,
    retained: false,
    payload: 'DeviceEvent',
  },
  'gp/v1/<gatewayId>/config': {
    direction: 'cloud_to_gateway',
    qos: 1,
    retained: true,
    payload: 'GatewayConfig',
  },
  'gp/v1/<gatewayId>/cmd': { direction: 'cloud_to_gateway', qos: 1, retained: false, payload: 'Command' },
  'gp/v1/<gatewayId>/cmd/ack': {
    direction: 'gateway_to_cloud',
    qos: 1,
    retained: false,
    payload: 'CommandAck',
  },
} as const;

type Schema = Record<string, unknown>;

const ENUM_NAMES = new Map<string, string>(
  Object.entries(enums)
    .filter(([, value]) => typeof value === 'object')
    .map(([name, value]) => [JSON.stringify(Object.values(value as Record<string, string>)), name]),
);

const ISO_ONE_OF = JSON.stringify([
  { format: 'date', type: 'string' },
  { format: 'date-time', type: 'string' },
]);

/**
 * JSON Schema draft 2020-12 of the MQTT payloads, generated from the very DTO classes the ingest
 * process validates with (contract §7, D-130). Deterministic: keys sorted, enums as named `$defs`,
 * ISO 8601 fields as `format: date-time`, nullable fields required.
 */
export function buildDeviceProtocolSchema(version: string): Schema {
  const generated = validationMetadatasToSchemas({
    classValidatorMetadataStorage: getMetadataStorage(),
    classTransformerMetadataStorage: defaultMetadataStorage,
    refPointerPrefix: '#/$defs/',
    additionalConverters: { uniqueReadingSeq: {} },
  }) as Record<string, Schema>;

  const defs: Record<string, Schema> = {};
  for (const payload of PROTOCOL_PAYLOADS) {
    const schema = generated[payload.name];
    if (!schema) throw new Error(`No validation metadata for ${payload.name}`);
    defs[payload.name] = { title: payload.name, ...normaliseDefinition(schema, defs) };
  }

  return sortKeys({
    $schema: JSON_SCHEMA_DRAFT,
    $id: DEVICE_PROTOCOL_SCHEMA_ID,
    title: 'getproperty device protocol v1',
    description:
      'MQTT payloads between getproperty-edge and getproperty-api (docs/contract/device-protocol.md, D-130). ' +
      'Generated by `pnpm contract:build` from the DTO classes the ingest process validates with; never edited by hand.',
    'x-api-version': version,
    'x-topics': TOPICS,
    'x-lwt': { topic: 'gp/v1/<gatewayId>/health', payload: { status: 'offline_lwt' } },
    $defs: defs,
  });
}

function normaliseDefinition(schema: Schema, defs: Record<string, Schema>): Schema {
  const out: Schema = { ...schema, additionalProperties: schema.additionalProperties ?? false };
  const properties = { ...((schema.properties as Record<string, Schema>) ?? {}) };
  const required = new Set<string>((schema.required as string[]) ?? []);
  for (const [name, property] of Object.entries(properties)) {
    properties[name] = normaliseProperty(property, defs);
    const type = properties[name].type;
    // A nullable field is always present on the wire (device-protocol.md §3: `"rssi": null`).
    if (Array.isArray(type) && type.includes('null')) required.add(name);
  }
  out.properties = properties;
  out.required = [...required].sort();
  return out;
}

function normaliseProperty(property: Schema, defs: Record<string, Schema>): Schema {
  let out: Schema = { ...property };
  if (JSON.stringify(out.oneOf) === ISO_ONE_OF) {
    const { oneOf: _oneOf, ...rest } = out;
    out = { ...rest, type: rest.type ?? 'string', format: 'date-time' };
  }
  if (Array.isArray(out.enum) && typeof out.enum[0] === 'string') {
    const enumName = ENUM_NAMES.get(JSON.stringify(out.enum));
    if (enumName) {
      defs[enumName] = { title: enumName, type: 'string', enum: out.enum };
      const { enum: _enum, type: _type, ...rest } = out;
      out = { ...rest, $ref: `#/$defs/${enumName}` };
    }
  }
  if (out.items && typeof out.items === 'object') out.items = normaliseProperty(out.items as Schema, defs);
  return out;
}

export function sortKeys<T>(value: T): T {
  if (Array.isArray(value)) return value.map((item: unknown) => sortKeys(item)) as T;
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map((key) => [key, sortKeys((value as Record<string, unknown>)[key])]),
    ) as T;
  }
  return value;
}
