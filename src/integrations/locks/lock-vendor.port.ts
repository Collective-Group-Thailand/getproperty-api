/**
 * Smart lock vendors (B5.2, D-070): TTLock and Tuya cloud adapters behind one port, a fake for dev/tests. A lock is
 * addressed by its vendor id; per-tenant vendor credentials come from the secret store
 * (`LOCKS_SECRETS_PREFIX/<vendor>/<tenantId>`), never from the database. There is deliberately no "lock the resident
 * out" operation: credentials are created and revoked one by one (D-024, D-071).
 */
export const LOCK_VENDORS = Symbol('LOCK_VENDORS');

export type LockVendorKey = 'ttlock' | 'tuya';
export const LOCK_VENDOR_KEYS: readonly LockVendorKey[] = ['ttlock', 'tuya'];

export interface LockRef {
  vendor: LockVendorKey;
  vendorLockId: string;
  /** Vendor account secrets of the tenant (API keys, account user / password). */
  credentials: Record<string, string>;
}

export interface CredentialInput {
  /** `pin`: a keypad code (the adapter returns the code it set); `card` / `app`: vendor dependent. */
  type: 'pin' | 'app' | 'card';
  holderName: string;
  /** A PIN chosen by the caller (6–9 digits); generated by the platform when omitted. */
  pin: string;
  validFrom: Date;
  /** null = permanent until revoked (residents: the lease decides). */
  validTo: Date | null;
}

export interface CreatedCredential {
  vendorCredentialRef: string;
}

export interface VendorUnlockEvent {
  vendorEventId: string;
  at: Date;
  result: 'success' | 'denied' | 'error';
  source: 'app' | 'pin' | 'card' | 'remote' | 'fingerprint' | 'face' | 'qr';
  /** The vendor credential that opened the lock, when the vendor reports it. */
  vendorCredentialRef: string | null;
  detail?: Record<string, unknown>;
}

export interface LockStatus {
  /** Battery 0–100 or null when the vendor did not say. */
  batteryPct: number | null;
  online: boolean | null;
}

export interface LockVendorAdapter {
  readonly vendor: LockVendorKey;
  readonly mode: 'fake' | 'real';
  createCredential(lock: LockRef, input: CredentialInput): Promise<CreatedCredential>;
  revokeCredential(lock: LockRef, vendorCredentialRef: string, type: CredentialInput['type']): Promise<void>;
  /** Unlock events after `since` (oldest first). */
  unlockLog(lock: LockRef, since: Date, until: Date): Promise<VendorUnlockEvent[]>;
  status(lock: LockRef): Promise<LockStatus>;
}

export interface LockVendorRegistry {
  readonly mode: 'fake' | 'real';
  adapter(vendor: LockVendorKey): LockVendorAdapter;
}

export class LockVendorError extends Error {
  constructor(
    readonly vendor: string,
    message: string,
  ) {
    super(`${vendor}: ${message}`);
    this.name = 'LockVendorError';
  }
}
