import { COMPLIANCE_RULES } from './rules';

interface OpenApiLike {
  paths?: Record<string, Record<string, unknown>>;
  webhooks?: Record<string, Record<string, unknown>>;
}

const METHODS = ['get', 'put', 'post', 'delete', 'patch'] as const;

/** Operation ids per compliance rule, from the `x-compliance-rules` of the published contract (`@ApiCompliance`). */
export function coveredOperations(document: OpenApiLike): Map<string, string[]> {
  const byRule = new Map<string, string[]>();
  for (const item of [...Object.values(document.paths ?? {}), ...Object.values(document.webhooks ?? {})])
    for (const method of METHODS) {
      const op = item[method] as { operationId?: string; 'x-compliance-rules'?: string[] } | undefined;
      for (const rule of op?.['x-compliance-rules'] ?? [])
        byRule.set(rule, [...(byRule.get(rule) ?? []), op!.operationId ?? `${method}`]);
    }
  for (const [k, v] of byRule) byRule.set(k, [...new Set(v)].sort());
  return byRule;
}

const cell = (s: string) => s.replace(/\|/g, '\\|');

/**
 * `docs/compliance.md` (`pnpm compliance:report`, B4.1 acceptance): the registry table — id, legal reference, default
 * severity, subjects, settings read, and the API operations that can raise the rule (from the contract).
 */
export function renderComplianceReport(document: OpenApiLike): string {
  const covered = coveredOperations(document);
  const lines = [
    '# Compliance rules — getproperty-api',
    '',
    '> Generated by `pnpm compliance:report` from `src/core/compliance/rules.ts` and `contract/openapi.json` — do not edit.',
    '> Engine: ADR-0007. Severity semantics (D-021a): `warn` = the Owner acknowledges (409 `compliance.acknowledgement_required`,',
    '> `platform.compliance_acknowledgement`) and repeats the request; `block` = refused (422 `compliance.*` with `legalRef`).',
    '> The platform admin overrides severities platform-wide or per tenant (`compliance.tariff_cap.severity`,',
    '> `compliance.severity_overrides`). Rules apply to tenants in scope of the สคบ. 2568 announcement (≥ 3 units, D-158).',
    '> Legal text: `docs/compliance/legal-reference.md` (⚖ pending legal verification, D-149).',
    '',
    `| Rule | Legal reference | Default severity | Applies to | Settings | Covered operations |`,
    `|---|---|---|---|---|---|`,
  ];
  for (const r of COMPLIANCE_RULES) {
    const ops = covered.get(r.id) ?? [];
    lines.push(
      `| \`${r.id}\` | ${cell(r.legalRef)} | ${r.defaultSeverity} | ${r.appliesTo.join(', ')} | ${
        r.settingsUsed.length ? r.settingsUsed.map((s) => `\`${s}\``).join(', ') : '—'
      } | ${ops.length ? ops.map((o) => `\`${o}\``).join(', ') : '— (engine/worker only)'} |`,
    );
  }
  lines.push('', `${COMPLIANCE_RULES.length} rules.`, '');
  return lines.join('\n');
}
